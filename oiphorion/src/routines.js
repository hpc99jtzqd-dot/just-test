/* 시험 주말: 공부 블록은 슬라이드 기준으로, 나머지는 수업 없는 날 루틴을 쓴다. */
const R_EXAM_DESK=["책상 위엔 슬라이드 · 노트 · 펜 · 질문 목록만","노트북은 슬라이드 창 하나만, 휴대폰은 방해 금지 → 가방 속","물 한 컵 (오전이면 커피 한 잔)","타이머 50분: 이번 블록에서 볼 장 번호를 먼저 적는다"];
const R_EXAM_END="블록이 끝날 때마다 지금 몇 장인지 표시";
function routineExam(plan,second){
  for(const b of plan){
    if(["morning","afternoon","evening"].includes(b.id)) b.steps=[...(b.id==="evening"?["저녁밥 → 설거지 · 양치 → 19:00 책상"]:[]),...R_EXAM_DESK,
      ...(second?["10장 읽고 덮기 → 백지에 핵심 쓰기 → 펼쳐서 빨간 펜으로 채점"]:["장마다 '이 장이 묻는 것' 한 줄 · 모르면 질문 목록에"]),...R_BREAK,R_EXAM_END];
    else if(b.id==="lunch") b.steps=["점심 차려 먹기 · 설거지 · 양치","13:00 책상: 오전 범위 펼쳐 두기","문제 하나만, 고민 없이 바로 (10분)"];
    else if(b.id==="minimum") b.steps=["시작 시각을 정하고 책상 정리 1분",...R_EXAM_DESK.slice(1),"할 일 순서대로, 막히면 넘어간다","끝나면 '막아 낸 날' 체크"];
    else if(b.id==="closing") b.steps=second  // 시험 주말 마감 칸은 23:00 (할 일과 같은 시각)
      ?[R_SHUTDOWN()[0],"가방: A4 요약 · 필기구 · 학생증 · 노트북","내일 옷 꺼내 두기 · 월 09:30 출발 알람",...R_WASH_NIGHT]
      :[...R_SHUTDOWN(),"질문 목록 맨 위 3개에 표시: 내일 아침 첫 블록","내일 옷 꺼내 두기 · 물컵 채워 두기",...R_WASH_NIGHT];
    else if(ROUTINE_FREE[b.id]) Object.assign(b,ROUTINE_FREE[b.id]);
  }
}

